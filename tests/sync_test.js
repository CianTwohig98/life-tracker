const S = require('../src/sync_core.js'), E = require('../src/engine.js');
let fails = 0; const ok = (c, m) => { console.log((c ? '  ok  ' : '  FAIL ') + m); if (!c) fails++; };
const mkDev = () => { const s = E.defaultState('2026-11-01'); return { s, h: S.stamp(s, null, 0) }; };
const edit = (dev, fn, t) => { fn(dev.s); dev.h = S.stamp(dev.s, dev.h, t); };
console.log('sync merge');
const A = mkDev(), B = mkDev();
edit(A, s => { s.logs['2026-11-10'] = { v: { sleep_dur: 8 }, slots: { morning: {} } }; }, 100);
edit(B, s => { s.logs['2026-11-11'] = { v: { sleep_dur: 7 }, slots: { morning: {} } }; }, 110);
let m = S.merge(A.s, B.s);
ok(Object.keys(m.logs).sort().join() === '2026-11-10,2026-11-11', 'days from both devices are kept');
edit(A, s => { s.logs['2026-11-11'] = { v: { sleep_dur: 9 }, slots: { morning: {} } }; }, 200);
edit(B, s => { s.logs['2026-11-11'].v.sleep_dur = 6; }, 150);
m = S.merge(A.s, B.s); ok(m.logs['2026-11-11'].v.sleep_dur === 9, 'same day edited on both: newer edit wins (9, not 6)');
m = S.merge(B.s, A.s); ok(m.logs['2026-11-11'].v.sleep_dur === 9, 'merge is symmetric');
edit(B, s => { s.todos.push({ id: 'x', text: 'plant', done: null }); }, 300);
m = S.merge(A.s, B.s); ok(m.todos.length === 1, 'todos travel (misc section newer on B)');
edit(A, s => { s.config.settings.kcal = 2222; }, 400);
m = S.merge(A.s, B.s); ok(m.config.settings.kcal === 2222 && m.todos.length === 1, 'config and todos each take their own newest version');
const fresh = mkDev(); m = S.merge(fresh.s, A.s); ok(m.config.settings.kcal === 2222 && Object.keys(m.logs).length === 2, 'a brand-new device adopts the cloud data and config');
m = S.merge(A.s, fresh.s); ok(m.config.settings.kcal === 2222, 'an untouched device never overwrites real data');
ok(S.sameData(S.merge(A.s, A.s), A.s), 'merging with itself changes nothing');
const sa = S.merge(A.s, B.s); const before = JSON.stringify(sa); S.merge(sa, B.s); ok(JSON.stringify(sa) === before, 'merge does not mutate its inputs');
console.log(fails ? fails + ' FAILED' : 'SYNC ALL PASSED'); process.exit(fails ? 1 : 0);
